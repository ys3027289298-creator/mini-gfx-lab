#!/usr/bin/env python3
"""Deterministic pseudo-measurement of per-elevation binaural reference curves.

The spatializer's elevation model is validated against these numbers angle by
angle. Regenerate the embedded table with:

    python3 -I tools/gen_reference.py > src/reference_data.h

Curves (elevation el in degrees, -90 = underfoot, +90 = overhead):
  itd_factor: relative interaural delay, geometric truth cos(el) (1 at the
              horizon, 0 at either pole) plus small measurement noise.
  hf_db:      pinna high-frequency shelf gain in dB; truth is a quadratic in
              sin(el) -- asymmetric, so overhead and underfoot do not match --
              plus small measurement noise.
"""
import math
import random

ANGLE_STEP = 15
SEED = 20261121
ITD_NOISE = 0.015
HF_NOISE = 0.12


def hf_truth(el):
    s = math.sin(math.radians(el))
    return -2.0 + 5.0 * s - 3.0 * s * s


def main():
    rng = random.Random(SEED)
    angles = list(range(-90, 91, ANGLE_STEP))
    itd, hf = [], []
    for el in angles:
        itd_meas = math.cos(math.radians(el)) + rng.uniform(-ITD_NOISE, ITD_NOISE)
        itd.append(min(1.0, max(0.0, itd_meas)))
        hf.append(hf_truth(el) + rng.uniform(-HF_NOISE, HF_NOISE))

    print("/* generated by tools/gen_reference.py - do not edit by hand. */")
    print("#ifndef REFERENCE_DATA_H")
    print("#define REFERENCE_DATA_H")
    print()
    print("#define REF_N %d" % len(angles))
    print("static const float ref_elev_deg[REF_N] = {")
    print("    " + ", ".join("%.1ff" % float(a) for a in angles))
    print("};")
    print("static const float ref_itd_factor[REF_N] = {")
    print("    " + ", ".join("%.4ff" % v for v in itd))
    print("};")
    print("static const float ref_hf_db[REF_N] = {")
    print("    " + ", ".join("%.3ff" % v for v in hf))
    print("};")
    print()
    print("#endif /* REFERENCE_DATA_H */")


if __name__ == "__main__":
    main()
